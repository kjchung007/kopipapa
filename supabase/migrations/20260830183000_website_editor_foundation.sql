create table if not exists public.website_pages (
  id bigint generated by default as identity primary key,
  title text not null check (length(title) between 1 and 120),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  seo_title text not null default '' check (length(seo_title) <= 70),
  seo_description text not null default '' check (length(seo_description) <= 180),
  draft_content jsonb not null default '{"sections":[]}'::jsonb,
  published_content jsonb,
  published_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (jsonb_typeof(draft_content) = 'object'),
  check (published_content is null or jsonb_typeof(published_content) = 'object')
);

create table if not exists public.website_page_versions (
  id bigint generated by default as identity primary key,
  page_id bigint not null references public.website_pages(id) on delete cascade,
  version_number integer not null,
  content jsonb not null check (jsonb_typeof(content) = 'object'),
  seo_title text not null default '',
  seo_description text not null default '',
  published_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  unique(page_id,version_number)
);

create table if not exists public.website_redirects (
  id bigint generated by default as identity primary key,
  from_path text not null unique check (from_path like '/%'),
  to_path text not null check (to_path like '/%'),
  status_code integer not null default 308 check (status_code in (301,302,307,308)),
  active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (from_path <> to_path)
);

create table if not exists public.website_assets (
  id bigint generated by default as identity primary key,
  storage_path text not null unique,
  public_url text not null,
  file_name text not null,
  mime_type text not null check (mime_type like 'image/%'),
  width integer check (width is null or width > 0),
  height integer check (height is null or height > 0),
  alt_text text not null default '',
  uploaded_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists website_pages_published_idx
  on public.website_pages(slug) where published_content is not null;
create index if not exists website_page_versions_page_created_idx
  on public.website_page_versions(page_id,created_at desc);

alter table public.website_pages enable row level security;
alter table public.website_page_versions enable row level security;
alter table public.website_redirects enable row level security;
alter table public.website_assets enable row level security;

