create or replace function public.publish_website_page(p_page_id bigint)
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare
  v_user uuid := (select auth.uid());
  v_page public.website_pages;
  v_version integer;
begin
  if v_user is null or not exists(
    select 1 from public.staff s
    where s.user_id=v_user and s.active and s.role='global_admin'::public.admin_role
  ) then raise exception 'Global administrator access required'; end if;

  select * into v_page from public.website_pages where id=p_page_id for update;
  if v_page.id is null then raise exception 'Website page not found'; end if;
  if jsonb_array_length(coalesce(v_page.draft_content->'sections','[]'::jsonb))=0 then
    raise exception 'Add at least one section before publishing';
  end if;

  select coalesce(max(version_number),0)+1 into v_version
  from public.website_page_versions where page_id=p_page_id;
  insert into public.website_page_versions(page_id,version_number,content,seo_title,seo_description,published_by)
  values(v_page.id,v_version,v_page.draft_content,v_page.seo_title,v_page.seo_description,v_user);
  update public.website_pages set published_content=draft_content,published_at=now(),updated_at=now(),updated_by=v_user
  where id=p_page_id;
  insert into public.admin_audit_logs(admin_id,action_type,target_id,details_json)
  values(v_user,'website.page_published',p_page_id::text,jsonb_build_object('slug',v_page.slug,'version',v_version));
  return jsonb_build_object('ok',true,'version',v_version,'slug',v_page.slug);
end $$;
revoke all on function public.publish_website_page(bigint) from public,anon;
grant execute on function public.publish_website_page(bigint) to authenticated;

create or replace function public.restore_website_page_version(p_version_id bigint)
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare v_user uuid := (select auth.uid()); v_version public.website_page_versions;
begin
  if v_user is null or not exists(select 1 from public.staff s where s.user_id=v_user and s.active and s.role='global_admin'::public.admin_role)
    then raise exception 'Global administrator access required'; end if;
  select * into v_version from public.website_page_versions where id=p_version_id;
  if v_version.id is null then raise exception 'Website version not found'; end if;
  update public.website_pages set draft_content=v_version.content,seo_title=v_version.seo_title,
    seo_description=v_version.seo_description,updated_by=v_user,updated_at=now() where id=v_version.page_id;
  insert into public.admin_audit_logs(admin_id,action_type,target_id,details_json)
  values(v_user,'website.version_restored',v_version.page_id::text,jsonb_build_object('version_id',v_version.id,'version',v_version.version_number));
  return jsonb_build_object('ok',true,'page_id',v_version.page_id);
end $$;
revoke all on function public.restore_website_page_version(bigint) from public,anon;
grant execute on function public.restore_website_page_version(bigint) to authenticated;

