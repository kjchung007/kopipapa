create or replace function private.award_completed_order_rewards() returns trigger language plpgsql security definer set search_path='' as $$
declare v_settings public.reward_settings%rowtype; v_points integer; v_stamps integer; v_rewards integer; v_template public.voucher_templates%rowtype;
begin
  if new.status <> 'completed' or old.status = 'completed' or new.user_id is null then return new; end if;
  if coalesce((select is_anonymous from auth.users where id=new.user_id),false) then return new; end if;
  select * into v_settings from public.reward_settings where id=true;
  insert into public.reward_accounts(user_id) values(new.user_id) on conflict(user_id) do nothing;
  if v_settings.active_system='points' then
    v_points=floor(new.total_cents::numeric*v_settings.points_per_rm/100)::integer;
    update public.reward_accounts set points_balance=points_balance+v_points,lifetime_points=lifetime_points+v_points,updated_at=now() where user_id=new.user_id;
    insert into public.reward_ledger(user_id,order_id,entry_type,points_delta,note) values(new.user_id,new.id,'points_earned',v_points,'Points from '||new.order_number) on conflict do nothing;
  else
    select coalesce(sum(quantity),0)::integer into v_stamps from public.order_items where order_id=new.id;
    update public.reward_accounts set stamp_count=stamp_count+v_stamps,updated_at=now() where user_id=new.user_id returning stamp_count/v_settings.stamp_threshold into v_rewards;
    insert into public.reward_ledger(user_id,order_id,entry_type,stamps_delta,note) values(new.user_id,new.id,'stamps_earned',v_stamps,'Stamps from '||new.order_number) on conflict do nothing;
    if v_rewards>0 and v_settings.stamp_reward_template_id is not null then
      select * into v_template from public.voucher_templates where id=v_settings.stamp_reward_template_id and active;
      if found then
        insert into public.user_vouchers(user_id,voucher_template_id,source,expires_at) select new.user_id,v_template.id,'stamp_reward',v_template.expires_at from generate_series(1,v_rewards);
        update public.reward_accounts set stamp_count=stamp_count-(v_rewards*v_settings.stamp_threshold) where user_id=new.user_id;
      end if;
    end if;
  end if;
  return new;
end $$;
drop trigger if exists award_completed_order_rewards on public.orders;
create trigger award_completed_order_rewards after update of status on public.orders for each row execute function private.award_completed_order_rewards();

create or replace function public.claim_voucher_code(p_code text) returns bigint language plpgsql security definer set search_path='' as $$
declare v_user uuid=(select auth.uid()); v_code public.voucher_codes%rowtype; v_template public.voucher_templates%rowtype; v_id bigint;
begin
  if v_user is null or coalesce(((select auth.jwt())->>'is_anonymous')::boolean,false) then raise exception 'Sign in with an account to claim rewards.'; end if;
  select * into v_code from public.voucher_codes where code=upper(trim(p_code)) for update;
  if not found or not v_code.active or v_code.claim_count>=v_code.max_claims or (v_code.expires_at is not null and v_code.expires_at<=now()) then raise exception 'This code is invalid, expired, or already claimed.'; end if;
  if exists(select 1 from public.user_vouchers where user_id=v_user and voucher_code_id=v_code.id) then raise exception 'You have already claimed this code.'; end if;
  select * into v_template from public.voucher_templates where id=v_code.voucher_template_id and active and (expires_at is null or expires_at>now());
  if not found then raise exception 'This voucher is no longer available.'; end if;
  insert into public.user_vouchers(user_id,voucher_template_id,voucher_code_id,source,expires_at) values(v_user,v_template.id,v_code.id,'secret_code',coalesce(v_code.expires_at,v_template.expires_at)) returning id into v_id;
  update public.voucher_codes set claim_count=claim_count+1,active=(claim_count+1<max_claims) where id=v_code.id;
  return v_id;
end $$;

create or replace function public.purchase_reward(p_template_id bigint) returns bigint language plpgsql security definer set search_path='' as $$
declare v_user uuid=(select auth.uid()); v_template public.voucher_templates%rowtype; v_id bigint;
begin
  if v_user is null or coalesce(((select auth.jwt())->>'is_anonymous')::boolean,false) then raise exception 'Sign in with an account to use rewards.'; end if;
  select * into v_template from public.voucher_templates where id=p_template_id and active and available_in_shop and point_cost is not null and (expires_at is null or expires_at>now()) for update;
  if not found then raise exception 'This reward is not available.'; end if;
  update public.reward_accounts set points_balance=points_balance-v_template.point_cost,updated_at=now() where user_id=v_user and points_balance>=v_template.point_cost;
  if not found then raise exception 'You do not have enough points.'; end if;
  insert into public.reward_ledger(user_id,entry_type,points_delta,note) values(v_user,'points_spent',-v_template.point_cost,'Purchased '||v_template.title);
  insert into public.user_vouchers(user_id,voucher_template_id,source,expires_at) values(v_user,v_template.id,'points_shop',v_template.expires_at) returning id into v_id;
  return v_id;
end $$;

create or replace function public.use_reward_voucher(p_user_voucher_id bigint) returns void language plpgsql security definer set search_path='' as $$
declare v_user uuid=(select auth.uid());
begin
  if v_user is null or coalesce(((select auth.jwt())->>'is_anonymous')::boolean,false) then
    raise exception 'Sign in with an account to use rewards.';
  end if;
  update public.user_vouchers
  set status='used',used_at=now()
  where id=p_user_voucher_id and user_id=v_user and status='active'
    and (expires_at is null or expires_at>now());
  if not found then raise exception 'This voucher is expired, used, or unavailable.'; end if;
end $$;

