create table if not exists public.reward_settings (
  id boolean primary key default true check (id),
  active_system text not null default 'points' check (active_system in ('stamp','points')),
  points_per_rm integer not null default 10 check (points_per_rm > 0),
  stamp_threshold integer not null default 8 check (stamp_threshold between 2 and 50),
  stamp_reward_template_id bigint,
  updated_at timestamptz not null default now()
);

create table if not exists public.voucher_templates (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 100),
  description text not null default '',
  voucher_type text not null check (voucher_type in ('buy_x_free_one','free_drink','amount_off')),
  buy_quantity integer check (buy_quantity between 1 and 50),
  amount_off_cents integer check (amount_off_cents > 0),
  valid_scope text not null default 'any_drink' check (valid_scope in ('any_drink','category','product')),
  category_id bigint references public.categories(id) on delete set null,
  product_id bigint references public.products(id) on delete set null,
  image_url text,
  expires_at timestamptz,
  point_cost integer check (point_cost is null or point_cost >= 0),
  available_in_shop boolean not null default false,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((voucher_type <> 'buy_x_free_one') or buy_quantity is not null),
  check ((voucher_type <> 'amount_off') or amount_off_cents is not null),
  check ((valid_scope <> 'category') or category_id is not null),
  check ((valid_scope <> 'product') or product_id is not null)
);

alter table public.reward_settings drop constraint if exists reward_settings_stamp_reward_template_id_fkey;
alter table public.reward_settings add constraint reward_settings_stamp_reward_template_id_fkey foreign key (stamp_reward_template_id) references public.voucher_templates(id) on delete set null;
insert into public.reward_settings(id) values(true) on conflict(id) do nothing;

create table if not exists public.voucher_codes (
  id bigint generated by default as identity primary key,
  voucher_template_id bigint not null references public.voucher_templates(id) on delete cascade,
  code text not null unique check (code = upper(code) and code ~ '^[A-Z0-9]{6,24}$'),
  max_claims integer not null default 1 check (max_claims > 0),
  claim_count integer not null default 0 check (claim_count >= 0 and claim_count <= max_claims),
  expires_at timestamptz,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.reward_accounts (
  user_id uuid primary key references auth.users(id) on delete cascade,
  points_balance integer not null default 0 check (points_balance >= 0),
  stamp_count integer not null default 0 check (stamp_count >= 0),
  lifetime_points integer not null default 0 check (lifetime_points >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.reward_ledger (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  order_id bigint references public.orders(id) on delete set null,
  entry_type text not null check (entry_type in ('points_earned','points_spent','stamps_earned','stamp_reward','manual_adjustment')),
  points_delta integer not null default 0,
  stamps_delta integer not null default 0,
  note text not null default '',
  created_at timestamptz not null default now()
);
create unique index if not exists reward_ledger_order_entry_key on public.reward_ledger(order_id,entry_type) where order_id is not null;
create index if not exists reward_ledger_user_created_idx on public.reward_ledger(user_id,created_at desc);
create index if not exists reward_settings_template_idx on public.reward_settings(stamp_reward_template_id);
create index if not exists voucher_templates_category_idx on public.voucher_templates(category_id);
create index if not exists voucher_templates_product_idx on public.voucher_templates(product_id);
create index if not exists voucher_codes_template_idx on public.voucher_codes(voucher_template_id);
create index if not exists user_vouchers_template_idx on public.user_vouchers(voucher_template_id);
create index if not exists user_vouchers_code_idx on public.user_vouchers(voucher_code_id);
