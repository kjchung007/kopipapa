create table if not exists public.user_vouchers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  voucher_template_id bigint not null references public.voucher_templates(id),
  voucher_code_id bigint references public.voucher_codes(id),
  source text not null check (source in ('secret_code','points_shop','stamp_reward','admin')),
  status text not null default 'active' check (status in ('active','used','expired')),
  claimed_at timestamptz not null default now(),
  used_at timestamptz,
  expires_at timestamptz,
  order_id bigint references public.orders(id) on delete set null,
  unique(user_id,voucher_code_id)
);
create index if not exists user_vouchers_user_status_idx on public.user_vouchers(user_id,status,claimed_at desc);

