create or replace function private.prepare_self_account_deletion_impl()
returns jsonb language plpgsql security definer set search_path=''
as $$
declare
  v_user uuid := (select auth.uid());
  v_deleted_subject constant uuid := '00000000-0000-0000-0000-000000000001'::uuid;
  v_orders integer := 0;
begin
  if v_user is null or coalesce(((select auth.jwt())->>'is_anonymous')::boolean,false) then
    raise exception 'Verified customer sign-in required';
  end if;
  if exists(select 1 from public.staff s where s.user_id=v_user) or exists(select 1 from public.admin_users a where a.user_id=v_user) then
    raise exception 'Team accounts must be removed by another global administrator';
  end if;

  update public.orders set
    user_id=null,
    anonymized_customer_id=v_deleted_subject,
    customer_name='Deleted customer',
    customer_email=null
  where user_id=v_user;
  get diagnostics v_orders = row_count;

  update public.reward_ledger set user_id=null,anonymized_customer_id=v_deleted_subject where user_id=v_user;
  delete from public.customer_cart_items where user_id=v_user;
  delete from public.user_vouchers where user_id=v_user;
  delete from public.reward_accounts where user_id=v_user;
  delete from public.profiles where user_id=v_user;
  return jsonb_build_object('prepared',true,'orders_anonymized',v_orders);
end $$;
revoke all on function private.prepare_self_account_deletion_impl() from public,anon,authenticated;
grant execute on function private.prepare_self_account_deletion_impl() to authenticated;

create or replace function public.prepare_self_account_deletion()
returns jsonb language plpgsql security invoker set search_path=''
as $$
begin
  if auth.uid() is null then raise exception 'Customer sign-in required'; end if;
  return private.prepare_self_account_deletion_impl();
end $$;
revoke all on function public.prepare_self_account_deletion() from public,anon;
grant execute on function public.prepare_self_account_deletion() to authenticated;

