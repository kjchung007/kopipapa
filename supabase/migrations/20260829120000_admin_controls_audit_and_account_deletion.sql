create table if not exists public.admin_audit_logs (
  id bigint generated by default as identity primary key,
  admin_id uuid references auth.users(id) on delete set null,
  action_type text not null check (length(action_type) between 3 and 80),
  target_id text,
  details_json jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists admin_audit_logs_created_idx
  on public.admin_audit_logs(created_at desc);
create index if not exists admin_audit_logs_action_created_idx
  on public.admin_audit_logs(action_type,created_at desc);
create index if not exists admin_audit_logs_admin_created_idx
  on public.admin_audit_logs(admin_id,created_at desc);

alter table public.admin_audit_logs enable row level security;
drop policy if exists global_admin_reads_audit_logs on public.admin_audit_logs;
create policy global_admin_reads_audit_logs on public.admin_audit_logs
  for select to authenticated using (
    exists (
      select 1 from public.staff s
      where s.user_id=(select auth.uid()) and s.active
        and s.role='global_admin'::public.admin_role
    )
    and not coalesce(((select auth.jwt())->>'is_anonymous')::boolean,false)
  );
revoke all on public.admin_audit_logs from public,anon,authenticated;
grant select on public.admin_audit_logs to authenticated;

create or replace function private.audit_admin_table_change()
returns trigger language plpgsql security definer set search_path=''
as $$
declare
  v_admin uuid := (select auth.uid());
  v_role public.admin_role;
  v_row jsonb := case when tg_op='DELETE' then to_jsonb(old) else to_jsonb(new) end;
begin
  if v_admin is null then if tg_op='DELETE' then return old; else return new; end if; end if;
  select s.role into v_role from public.staff s where s.user_id=v_admin and s.active limit 1;
  if v_role not in ('global_admin'::public.admin_role,'store_manager'::public.admin_role) then if tg_op='DELETE' then return old; else return new; end if; end if;
  insert into public.admin_audit_logs(admin_id,action_type,target_id,details_json)
    values(v_admin,lower(tg_table_name)||'.'||lower(tg_op),coalesce(v_row->>'id',v_row->>'user_id'),
      jsonb_build_object('table',tg_table_name,'operation',tg_op,'record',v_row));
  if tg_op='DELETE' then return old; else return new; end if;
end $$;
revoke all on function private.audit_admin_table_change() from public,anon,authenticated;

do $$
declare v_table text;
begin
  foreach v_table in array array['products','categories','stores','staff','campaigns','voucher_templates','reward_settings'] loop
    execute format('drop trigger if exists audit_admin_change on public.%I',v_table);
    execute format('create trigger audit_admin_change after insert or update or delete on public.%I for each row execute function private.audit_admin_table_change()',v_table);
  end loop;
end $$;

